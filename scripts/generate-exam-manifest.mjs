/**
 * Scans /data/exams and writes a static import manifest consumed by the
 * /exams/[paperId] route's generateStaticParams(). npm's predev, prebuild and
 * preverify:data hooks call this automatically, so adding a JSON file to
 * /data/exams is enough to publish a new page on the next git push.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const EXAMS_DIR = path.join(ROOT, "data", "exams");
const OUTPUT_DIR = path.join(ROOT, "src", "generated");
const OUTPUT_FILE = path.join(OUTPUT_DIR, "exam-manifest.ts");

const files = readdirSync(EXAMS_DIR)
  .filter((file) => file.endsWith(".json"))
  .sort();

if (files.length === 0) {
  throw new Error(`No exam JSON files found in ${EXAMS_DIR}`);
}

const ids = new Set();
const lines = [
  "/** Generated by scripts/generate-exam-manifest.mjs — do not edit. */",
  'import type { ExamPaper } from "../types/exam";',
  "",
];

for (const [index, file] of files.entries()) {
  const id = file.replace(/\.json$/, "");
  if (!/^n[1-5]-[a-z0-9-]+$/.test(id)) {
    throw new Error(
      `Invalid exam filename "${file}". Use <level>-<slug>.json, e.g. n5-sample-01.json.`,
    );
  }

  const raw = readFileSync(path.join(EXAMS_DIR, file), "utf8");
  let paper;
  try {
    paper = JSON.parse(raw);
  } catch (error) {
    throw new Error(`Invalid JSON in data/exams/${file}: ${error.message}`);
  }
  if (paper.id !== id) {
    throw new Error(`data/exams/${file}: "id" must be "${id}"`);
  }
  if (ids.has(id)) {
    throw new Error(`Duplicate exam paper id "${id}"`);
  }
  ids.add(id);

  lines.push(`import paper${index} from "../../data/exams/${file}";`);
}

lines.push(
  "",
  "export const examPapers: ExamPaper[] = [",
  ...files.map((_, index) => `  paper${index} as unknown as ExamPaper,`),
  "];",
  "",
  `export const examPaperIds = ${JSON.stringify([...ids]) } as const;`,
  "",
);

mkdirSync(OUTPUT_DIR, { recursive: true });
writeFileSync(OUTPUT_FILE, lines.join("\n"), "utf8");
console.log(
  `Generated src/generated/exam-manifest.ts with ${files.length} exam paper(s).`,
);
